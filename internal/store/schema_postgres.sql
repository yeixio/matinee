-- Same tables as schema_sqlite.sql. Booleans stay integers (0/1) so both
-- databases take the same queries.
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    is_admin      INTEGER NOT NULL DEFAULT 0,
    created_at    BIGINT NOT NULL
);
CREATE UNIQUE INDEX users_username ON users (lower(username));

CREATE TABLE sessions (
    token      TEXT PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at BIGINT NOT NULL
);

CREATE TABLE libraries (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT NOT NULL,
    kind       TEXT NOT NULL,
    created_at BIGINT NOT NULL
);

CREATE TABLE library_paths (
    library_id BIGINT NOT NULL REFERENCES libraries(id) ON DELETE CASCADE,
    path       TEXT NOT NULL,
    PRIMARY KEY (library_id, path)
);

CREATE TABLE items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    library_id     BIGINT NOT NULL REFERENCES libraries(id) ON DELETE CASCADE,
    parent_id      BIGINT REFERENCES items(id) ON DELETE CASCADE,
    kind           TEXT NOT NULL,
    title          TEXT NOT NULL,
    sort_title     TEXT NOT NULL,
    year           INTEGER,
    index_number   INTEGER,
    disc_number    INTEGER,
    path           TEXT UNIQUE,
    size           BIGINT,
    mtime          BIGINT,
    duration_ms    BIGINT,
    container      TEXT,
    video_codec    TEXT,
    audio_codec    TEXT,
    width          INTEGER,
    height         INTEGER,
    overview       TEXT,
    rating         DOUBLE PRECISION,
    poster         TEXT,
    backdrop       TEXT,
    tmdb_id        BIGINT,
    meta_at        BIGINT,
    added_at       BIGINT NOT NULL
);
CREATE INDEX items_parent ON items(parent_id, index_number, sort_title);
CREATE INDEX items_library ON items(library_id, kind, sort_title);
CREATE INDEX items_added ON items(added_at);
CREATE UNIQUE INDEX items_container_key ON items(library_id, kind, COALESCE(parent_id, 0), title, COALESCE(index_number, -1)) WHERE path IS NULL;
CREATE INDEX items_title_search ON items USING GIN (to_tsvector('simple', title));

CREATE TABLE progress (
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    item_id     BIGINT NOT NULL REFERENCES items(id) ON DELETE CASCADE,
    position_ms BIGINT NOT NULL DEFAULT 0,
    played      INTEGER NOT NULL DEFAULT 0,
    updated_at  BIGINT NOT NULL,
    PRIMARY KEY (user_id, item_id)
);
CREATE INDEX progress_recent ON progress(user_id, updated_at);
